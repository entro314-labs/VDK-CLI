/**
 * OpenAI Codex CLI Integration Module
 * ------------------------------------
 * Context Platform Integration: OpenAI Codex CLI
 *
 * OpenAI Codex is a Rust-based terminal AI assistant included with ChatGPT Plus/Pro/Enterprise.
 * Uses AGENTS.md format for project-specific instructions with hierarchical discovery.
 * Context Format: AGENTS.md with AGENTS.override.md for overrides
 * Priority: HIGH (Important platform)
 */

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { BaseIntegration } from './base-integration.js';

export class OpenAICodexIntegration extends BaseIntegration {
  constructor(projectPath = process.cwd()) {
    super('OpenAI Codex', projectPath);
    this.codexConfigPath = path.join(os.homedir(), '.codex');
  }

  getConfigPaths() {
    return {
      projectAgents: path.join(this.projectPath, 'AGENTS.md'),
      projectAgentsOverride: path.join(this.projectPath, 'AGENTS.override.md'),
      globalConfig: path.join(this.codexConfigPath, 'config.toml'),
      globalAgents: path.join(this.codexConfigPath, 'AGENTS.md'),
      globalAgentsOverride: path.join(this.codexConfigPath, 'AGENTS.override.md'),
    };
  }

  detectUsage() {
    const detection = this.createDetectionResult();
    const paths = this.getConfigPaths();

    // Check for project-level AGENTS files
    this.checkPaths(
      detection,
      {
        'Found AGENTS.md': paths.projectAgents,
        'Found AGENTS.override.md': paths.projectAgentsOverride,
      },
      'high',
      true
    );

    // Check for global Codex installation
    this.checkPaths(
      detection,
      {
        'Found ~/.codex/config.toml': paths.globalConfig,
        'Found ~/.codex/AGENTS.md': paths.globalAgents,
      },
      'medium'
    );

    // Check for codex command
    if (this.commandExists('codex')) {
      detection.indicators.push('Codex CLI command is available');
      if (detection.confidence === 'none') {
        detection.confidence = 'medium';
      }
    }

    return detection;
  }

  async initialize(options = {}) {
    const paths = this.getConfigPaths();

    try {
      // Create AGENTS.md following OpenAI Codex conventions
      const agentsContent = `# Repository: ${options.projectName || path.basename(this.projectPath)}

## Build and Test Commands
- Build: ${options.buildCommand || 'npm run build'}
- Test: ${options.testCommand || 'npm test'}
- Lint: ${options.lintCommand || 'npm run lint'}
- Format: ${options.formatCommand || 'npm run format'}

## Code Standards
- Follow ${options.primaryLanguage || 'project'} idioms and official style guide
- Use proper error handling (no uncaught exceptions)
- Document all public APIs
- Include unit tests for all business logic

## Architecture
${options.description || 'Project architecture and key components'}

## Technology Stack
- ${options.primaryLanguage || 'Multiple languages'}
- ${options.framework || 'Framework/libraries used'}
- ${options.database || 'Database system'}

## Dependencies Management
- Review dependencies regularly
- Run security audits
- Discuss before adding new dependencies

*Generated by VDK CLI - Use \`codex /init\` to regenerate*
`;

      if (!this.fileExists(paths.projectAgents)) {
        await fs.promises.writeFile(paths.projectAgents, agentsContent, 'utf8');
      }

      // Add to gitignore
      await this.ensureGitignoreEntry('AGENTS.override.md');

      return true;
    } catch (error) {
      console.error('Failed to initialize OpenAI Codex configuration:', error.message);
      return false;
    }
  }

  // ============================================================================
  // V3.0 COMPONENT METHODS
  // ============================================================================

  getComponentPaths() {
    return {
      main: path.join(this.projectPath, 'AGENTS.md'),
      agents: null, // Codex uses AGENTS.md, not separate agent files
      rules: null,
      commands: null,
      skills: null,
      workflows: null,
      settings: path.join(this.codexConfigPath, 'config.toml'),
      mcpConfig: null, // MCP configured in config.toml
    };
  }

  getPlatformConstraints() {
    return {
      maxCharacters: null,
      maxFiles: null,
      maxDepth: null,
      supportsFileReferences: true,
      supportsYAMLFrontmatter: false,
      supportsAgents: true,
      supportsRules: true, // true to allow RuleAdapter adaptation
      supportsCommands: false,
      supportsSkills: false,
      supportsWorkflows: false,
      supportsMCP: false,
      globPatternSyntax: null,
    };
  }

  async parseMainComponent(filePath) {
    try {
      const content = await fs.promises.readFile(filePath, 'utf8');

      return {
        type: 'main',
        name: 'AGENTS',
        file: filePath,
        content,
        format: 'markdown',
        platform: 'openai-codex',
      };
    } catch (error) {
      console.error(`Error parsing main component ${filePath}:`, error);
      return null;
    }
  }

  async generateComponents(components, _options = {}) {
    const result = {
      success: true,
      files: [],
      errors: [],
      warnings: [],
    };

    try {
      // Codex only supports AGENTS.md main file
      if (components.main) {
        try {
          const agentsPath = path.join(this.projectPath, 'AGENTS.md');
          await fs.promises.writeFile(agentsPath, components.main.content, 'utf8');
          result.files.push({ type: 'main', path: agentsPath });
        } catch (error) {
          result.errors.push(`Failed to generate AGENTS.md: ${error.message}`);
        }
      }

      // Merge agents into main file (Codex doesn't support separate agent files)
      if (components.agents && components.agents.length > 0) {
        result.warnings.push(
          `OpenAI Codex uses AGENTS.md format. ${components.agents.length} agents will be merged into main file.`
        );
      }

      // Warn about unsupported components
      if (components.rules && components.rules.length > 0) {
        result.warnings.push(
          `OpenAI Codex doesn't support separate rules. ${components.rules.length} rules should be included in AGENTS.md.`
        );
      }
      if (components.commands && components.commands.length > 0) {
        result.warnings.push(
          `OpenAI Codex doesn't support custom commands. ${components.commands.length} commands will be ignored.`
        );
      }

      result.success = result.errors.length === 0;
    } catch (error) {
      result.success = false;
      result.errors.push(`Component generation failed: ${error.message}`);
    }

    return result;
  }
}
