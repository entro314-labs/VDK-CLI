/**
 * Google Gemini CLI (Code Assist) Integration Module
 * ---------------------------------------------------
 * Context Platform Integration: Google Gemini CLI
 *
 * Gemini CLI is Google's open-source terminal agent using ReAct (Reason and Act) planning loop.
 * Uses .gemini/settings.json for MCP config and .gemini/styleguide.md for coding rules (Enterprise).
 * Context Format: .gemini/ directory with settings and styleguide
 * Priority: HIGH (Important platform)
 */

import fs from 'node:fs';
import path from 'node:path';

import { BaseIntegration } from './base-integration.js';

export class GeminiCLIIntegration extends BaseIntegration {
  constructor(projectPath = process.cwd()) {
    super('Gemini CLI', projectPath);
    this.geminiConfigPath = path.join(projectPath, '.gemini');
  }

  getConfigPaths() {
    return {
      projectSettings: path.join(this.geminiConfigPath, 'settings.json'),
      projectStyleguide: path.join(this.geminiConfigPath, 'styleguide.md'),
    };
  }

  detectUsage() {
    const detection = this.createDetectionResult();
    const paths = this.getConfigPaths();

    this.checkPaths(
      detection,
      {
        'Project has .gemini directory': this.geminiConfigPath,
        'Found .gemini/settings.json': paths.projectSettings,
        'Found .gemini/styleguide.md': paths.projectStyleguide,
      },
      'high',
      true
    );

    // Check for gemini command
    if (this.commandExists('gemini')) {
      detection.indicators.push('Gemini CLI command is available');
      if (detection.confidence === 'none') {
        detection.confidence = 'medium';
      }
    }

    // Check for GEMINI_API_KEY environment variable
    if (process.env.GEMINI_API_KEY) {
      detection.indicators.push('GEMINI_API_KEY environment variable is set');
      detection.confidence = 'high';
    }

    return detection;
  }

  async initialize(options = {}) {
    const paths = this.getConfigPaths();

    try {
      await this.ensureDirectory(this.geminiConfigPath);

      // Create settings.json for MCP server configuration
      const geminiSettings = {
        mcpServers: {},
        // MCP servers can be added here following MCP protocol
      };

      if (!this.fileExists(paths.projectSettings)) {
        await this.writeJsonFile(paths.projectSettings, geminiSettings);
      }

      // Create styleguide.md (Enterprise feature)
      const styleguideContent = `# ${options.projectName || 'Project'} Coding Standards

## Code Style
- Follow ${options.primaryLanguage || 'language'} idioms and best practices
- Use consistent formatting and naming conventions
- Write self-documenting code with clear variable names
- Add comments for complex logic only

## Architecture Patterns
${options.description || 'Project architecture guidelines'}

## Technology Stack
- ${options.primaryLanguage || 'Primary language'}
- ${options.framework || 'Framework/libraries'}
- ${options.database || 'Database system'}

## Testing Requirements
- Write unit tests for all business logic
- Include integration tests for API endpoints
- Maintain minimum ${options.coverageTarget || '80'}% code coverage
- Use appropriate mocking for external dependencies

## Error Handling
- Use proper error handling patterns
- Log errors with appropriate context
- Provide meaningful error messages
- Handle edge cases gracefully

## Dependencies
- Review dependencies before adding
- Keep dependencies up to date
- Run security audits regularly
- Document dependency choices

*Generated by VDK CLI - Gemini CLI Enterprise feature*
`;

      if (!this.fileExists(paths.projectStyleguide)) {
        await fs.promises.writeFile(paths.projectStyleguide, styleguideContent, 'utf8');
      }

      await this.ensureGitignoreEntry('.gemini/settings.local.json');

      return true;
    } catch (error) {
      console.error('Failed to initialize Gemini CLI configuration:', error.message);
      return false;
    }
  }

  // ============================================================================
  // V3.0 COMPONENT METHODS
  // ============================================================================

  getComponentPaths() {
    return {
      main: path.join(this.geminiConfigPath, 'styleguide.md'),
      agents: null, // Gemini uses ReAct loop, not separate agents
      rules: path.join(this.geminiConfigPath, 'styleguide.md'), // Rules in styleguide
      commands: null,
      skills: null,
      workflows: null,
      settings: path.join(this.geminiConfigPath, 'settings.json'),
      mcpConfig: path.join(this.geminiConfigPath, 'settings.json'), // MCP in settings
    };
  }

  getPlatformConstraints() {
    return {
      maxCharacters: null,
      maxFiles: null,
      maxDepth: null,
      supportsFileReferences: false,
      supportsYAMLFrontmatter: false,
      supportsAgents: false, // Uses ReAct loop instead
      supportsRules: true, // Via styleguide.md
      supportsCommands: false,
      supportsSkills: false,
      supportsWorkflows: false,
      supportsMCP: true, // Via settings.json
      globPatternSyntax: null,
    };
  }

  async parseMainComponent(filePath) {
    try {
      const content = await fs.promises.readFile(filePath, 'utf8');

      return {
        type: 'main',
        name: 'styleguide',
        file: filePath,
        content,
        format: 'markdown',
        platform: 'gemini-cli',
      };
    } catch (error) {
      console.error(`Error parsing styleguide ${filePath}:`, error);
      return null;
    }
  }

  async generateComponents(components, _options = {}) {
    const result = {
      success: true,
      files: [],
      errors: [],
      warnings: [],
    };

    try {
      // Generate styleguide.md (merges rules and main content)
      if (components.main || (components.rules && components.rules.length > 0)) {
        try {
          const styleguideContent = components.main?.content || '';
          const styleguidePathFile = path.join(this.geminiConfigPath, 'styleguide.md');
          await fs.promises.writeFile(styleguidePathFile, styleguideContent, 'utf8');
          result.files.push({ type: 'main', path: styleguidePathFile });
        } catch (error) {
          result.errors.push(`Failed to generate styleguide.md: ${error.message}`);
        }
      }

      // Generate settings.json with MCP config
      if (components.settings || components.mcpConfig) {
        try {
          const settingsPath = path.join(this.geminiConfigPath, 'settings.json');
          const settings = components.settings?.content || { mcpServers: {} };
          await this.writeJsonFile(settingsPath, settings);
          result.files.push({ type: 'settings', path: settingsPath });
        } catch (error) {
          result.errors.push(`Failed to generate settings: ${error.message}`);
        }
      }

      // Warn about unsupported components
      if (components.agents && components.agents.length > 0) {
        result.warnings.push(
          `Gemini CLI uses ReAct loop instead of agents. ${components.agents.length} agents will be merged into styleguide.md.`
        );
      }
      if (components.commands && components.commands.length > 0) {
        result.warnings.push(
          `Gemini CLI doesn't support custom commands. ${components.commands.length} commands will be ignored.`
        );
      }
      if (components.workflows && components.workflows.length > 0) {
        result.warnings.push(
          `Gemini CLI doesn't support workflows. ${components.workflows.length} workflows will be ignored.`
        );
      }

      result.success = result.errors.length === 0;
    } catch (error) {
      result.success = false;
      result.errors.push(`Component generation failed: ${error.message}`);
    }

    return result;
  }
}
